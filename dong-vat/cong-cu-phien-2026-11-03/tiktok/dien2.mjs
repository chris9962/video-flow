import { chromium } from '/Users/nguyentruong/.claude/skills/flow-chain-video/scripts/node_modules/playwright-core/index.mjs';
const [caption, out] = process.argv.slice(2);
const browser = await chromium.connectOverCDP('http://127.0.0.1:9222', { timeout: 5000 });
const page = browser.contexts()[0].pages().find((p) => p.url().includes('tiktokstudio/upload'));
const dlg = page.locator('[role="dialog"]').filter({ hasText: 'Labeling AI-generated content' });
if (await dlg.isVisible().catch(() => false)) await dlg.getByRole('button', { name: 'Turn on', exact: true }).click();
await page.waitForTimeout(1200);
const ai = page.locator('[role="switch"], input[type="checkbox"]').nth(4);
console.log('AI label =', await ai.evaluate((s) => s.getAttribute('aria-checked') ?? String(s.checked)));

const editor = page.locator('[contenteditable="true"]').first();
await editor.click();
await page.keyboard.press('Meta+A');
await page.keyboard.press('Backspace');
await page.waitForTimeout(500);
await page.keyboard.type(caption, { delay: 60 });
await page.waitForTimeout(1500);
console.log('caption =', JSON.stringify(await editor.innerText()));
await page.locator('text=Who can see this post').click();
await page.waitForTimeout(800);
console.log('caption sau khi rời ô =', JSON.stringify(await editor.innerText()));
await editor.scrollIntoViewIfNeeded();
await page.screenshot({ path: out });
await browser.close();
